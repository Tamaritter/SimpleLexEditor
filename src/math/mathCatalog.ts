export type MathEntry = {
  name: string;
  code: string;
  category: string;
  kind: "symbol" | "formula" | "environment";
  preview?: string;
  packages?: string[];
  keywords?: string;
};
const symbols = (
  category: string,
  pairs: [string, string][],
  keywords = "",
): MathEntry[] =>
  pairs.map(([name, code]) => ({
    name,
    code,
    category,
    kind: "symbol",
    keywords,
  }));
const formula = (
  name: string,
  code: string,
  category: string,
  keywords = "",
): MathEntry => ({
  name,
  code,
  category,
  kind: "formula",
  packages: ["amsmath", "amssymb"],
  keywords,
});
